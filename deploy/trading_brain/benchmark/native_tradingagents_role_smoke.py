"""Exercise *native* TradingAgents bull, bear and trader nodes with frozen data.

All LLM responses are deterministic fakes. This tests actual upstream role
wiring without spending inference credits, accessing market APIs or placing
orders. It is not a live TradingAgents forecast.
"""
from __future__ import annotations

import json
from pathlib import Path

from langchain_core.messages import AIMessage
from tradingagents.agents.researchers.bull_researcher import create_bull_researcher
from tradingagents.agents.researchers.bear_researcher import create_bear_researcher
from tradingagents.agents.trader.trader import create_trader

from trading_brain_benchmark import load_fixture, observation_only


class OfflineLLM:
    def __init__(self):
        self.calls = []

    def with_structured_output(self, _schema):
        raise NotImplementedError("Test fixture deliberately forces offline text fallback")

    def invoke(self, prompt):
        self.calls.append(prompt)
        if isinstance(prompt, str) and "Bull Analyst" in prompt:
            return AIMessage(content="Test-only bull response: price/volume hypotheses unverified.")
        if isinstance(prompt, str) and "Bear Analyst" in prompt:
            return AIMessage(content="Test-only bear response: spread and provenance uncertain.")
        return AIMessage(content="HOLD\nTest-only mocked decision, no verified intraday entry data.")


def run(path: Path):
    evidence=observation_only(load_fixture(path))
    llm=OfflineLLM()
    bull=create_bull_researcher(llm)
    bear=create_bear_researcher(llm)
    trader=create_trader(llm)
    count=0
    for row in evidence["candidates"]:
        symbol=row["ticker"]
        state={
            "company_of_interest":symbol,
            "instrument_context":(
                f"The instrument is EXACT ticker {symbol}. Exchange unverified. "
                "This is a frozen research-only historical snapshot."
            ),
            "asset_type":"stock",
            "trade_date":"2026-10-20",
            "market_report":json.dumps({
                "observation_timestamp_utc":evidence["observation_timestamp_utc"],
                "source":evidence["data_source"],
                "ticker":symbol,
                "facts":row,
                "limitations":evidence["limitations"],
            },sort_keys=True),
            "sentiment_report":"",
            "news_report":"",
            "fundamentals_report":"",
            "investment_debate_state":{
                "history":"","bull_history":"","bear_history":"",
                "current_response":"","count":0,
            },
            "investment_plan":"",
        }
        bull_out=bull(state)
        assert "Bull Analyst" in bull_out["investment_debate_state"]["history"]
        state.update(bull_out)
        bear_out=bear(state)
        assert "Bear Analyst" in bear_out["investment_debate_state"]["history"]
        assert "Bull Analyst" in bear_out["investment_debate_state"]["history"]
        state.update(bear_out)
        state["investment_plan"]=(
            "The following is debate text generated by a deterministic mock, "
            "not a real financial recommendation. "
            + state["investment_debate_state"]["history"]
        )
        traded=trader(state)
        assert "HOLD" in traded["trader_investment_plan"]
        assert len(traded["messages"])==1
        count+=1
    assert len(llm.calls)==count*3,(count,len(llm.calls))
    assert count==20
    print("NATIVE_TRADINGAGENTS_ROLES_SMOKE_PASS", "symbols",count,
          "mock_llm_calls",len(llm.calls),"real_model_calls",0,
          "broker_orders",0)


if __name__=="__main__":
    run(Path(__file__).with_name("alpaca_eod_20261020_20.json"))
